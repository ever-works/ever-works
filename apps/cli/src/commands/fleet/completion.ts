import { Command } from 'commander';
import chalk from 'chalk';
import { FLEET_EXIT } from './fleet-exit';

/**
 * `ever-works completion <bash|zsh|fish>` (FL-19 P3, T-21) — prints a shell
 * completion script for the whole command tree (the `fleet` group and its
 * families, verbs, aliases and options included), generated from the commands
 * this CLI actually registers, so it can never list a verb that does not
 * exist.
 *
 *   ever-works completion bash > ~/.ever-works-completion.bash && echo 'source ~/.ever-works-completion.bash' >> ~/.bashrc
 *   ever-works completion zsh  > "${fpath[1]}/_ever-works"
 *   ever-works completion fish > ~/.config/fish/completions/ever-works.fish
 *
 * Nothing is read from or sent to the platform.
 */

export const COMPLETION_SHELLS = ['bash', 'zsh', 'fish'] as const;
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

/** One command as the script sees it. */
export interface CompletionNode {
    name: string;
    aliases: string[];
    options: string[];
    children: CompletionNode[];
}

/** The tree of a commander program (hidden help commands left out). */
export function completionTree(command: Command): CompletionNode {
    return {
        name: command.name(),
        aliases: command.aliases(),
        options: command.options.map((option) => option.long ?? option.short ?? '').filter((flag) => flag.length > 0),
        children: command.commands.filter((child) => child.name() !== 'help').map((child) => completionTree(child)),
    };
}

/** Every path of words that names a command (aliases included) → what may follow it. */
export function completionTable(root: CompletionNode): Map<string, string[]> {
    const table = new Map<string, string[]>();
    const walk = (node: CompletionNode, path: string[]) => {
        const words = [...node.children.flatMap((child) => [child.name, ...child.aliases]), ...node.options, '--help'];
        table.set(path.join(' '), Array.from(new Set(words)));
        for (const child of node.children) {
            for (const name of [child.name, ...child.aliases]) walk(child, [...path, name]);
        }
    };
    walk(root, []);
    return table;
}

function quote(text: string): string {
    return `'${text.replace(/'/g, `'\\''`)}'`;
}

function bashScript(program: string, table: Map<string, string[]>): string {
    const fn = `__${program.replace(/[^A-Za-z0-9]/g, '_')}_complete`;
    const lines = [...table.entries()].map(([path, words]) => `    ${fn}_words[${quote(path)}]=${quote(words.join(' '))}`);
    return [
        `# ${program} completion (bash; zsh via bashcompinit) — generated by \`${program} completion\``,
        `declare -A ${fn}_words`,
        `${fn}_init() {`,
        ...lines,
        '}',
        `${fn}_init`,
        `${fn}() {`,
        '    local cur path word i',
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    path=""',
        '    for ((i = 1; i < COMP_CWORD; i++)); do',
        '        word="${COMP_WORDS[i]}"',
        '        if [[ -n "${' + fn + '_words["${path:+$path }$word"]+x}" ]]; then',
        '            path="${path:+$path }$word"',
        '        fi',
        '    done',
        `    COMPREPLY=( $(compgen -W "\${${fn}_words["$path"]}" -- "$cur") )`,
        '}',
        `complete -F ${fn} ${program}`,
        '',
    ].join('\n');
}

function zshScript(program: string, table: Map<string, string[]>): string {
    return [
        `#compdef ${program}`,
        '# zsh runs the bash completion through bashcompinit.',
        'autoload -U +X bashcompinit && bashcompinit',
        bashScript(program, table),
    ].join('\n');
}

function fishScript(program: string, root: CompletionNode): string {
    const out: string[] = [`# ${program} completion (fish) — generated by \`${program} completion\``];
    const walk = (node: CompletionNode, parents: string[]) => {
        const condition =
            parents.length === 0
                ? '__fish_use_subcommand'
                : `__fish_seen_subcommand_from ${parents[parents.length - 1]}`;
        for (const child of node.children) {
            for (const name of [child.name, ...child.aliases]) {
                out.push(`complete -c ${program} -f -n ${quote(condition)} -a ${quote(name)}`);
            }
        }
        if (parents.length > 0) {
            for (const option of node.options) {
                if (!option.startsWith('--')) continue;
                out.push(`complete -c ${program} -n ${quote(condition)} -l ${quote(option.slice(2))}`);
            }
        }
        for (const child of node.children) walk(child, [...parents, child.name]);
    };
    walk(root, []);
    out.push('');
    return out.join('\n');
}

/** The completion script for one shell. */
export function completionScript(shell: CompletionShell, root: CompletionNode): string {
    const program = root.name;
    if (shell === 'fish') return fishScript(program, root);
    const table = completionTable(root);
    return shell === 'zsh' ? zshScript(program, table) : bashScript(program, table);
}

export const completionCommand = new Command('completion')
    .description('Print a shell completion script (bash, zsh or fish)')
    .argument('<shell>', COMPLETION_SHELLS.join(' | '))
    .action(function (this: Command, shell: string) {
        if (!(COMPLETION_SHELLS as readonly string[]).includes(shell)) {
            process.stderr.write(`${chalk.red(`✗ invalid — <shell> is ${COMPLETION_SHELLS.join(', ')}`)}\n`);
            process.exit(FLEET_EXIT.usage);
        }
        let root: Command = this;
        while (root.parent) root = root.parent;
        process.stdout.write(completionScript(shell as CompletionShell, completionTree(root)));
        process.exit(FLEET_EXIT.ok);
    });
